"""손글씨 이미지를 MNIST 데이터와 같은 형태(28x28, 20x20 상자, 무게중심 정렬)로 바꾸는 전처리"""

import numpy as np
import torch
from PIL import Image

# MNIST 학습 때 사용하는 정규화 값 (train.py와 app.py가 함께 사용)
정규화_평균 = 0.1307
정규화_표준편차 = 0.3081

모델_입력_크기 = 28
숫자_상자_크기 = 20      # MNIST는 숫자를 20x20 상자에 맞춘 뒤 28x28 한가운데에 놓는다
글씨_판정_밝기 = 30      # 이 값보다 밝은 픽셀을 글씨로 본다


def 모델_입력_이미지_만들기(그림):
    """검은 배경/흰 글씨의 'L' 이미지를 MNIST 방식의 28x28 이미지로 변환한다. 글씨가 없으면 None."""
    배열 = np.array(그림, dtype=np.float32)
    좌표 = np.argwhere(배열 > 글씨_판정_밝기)
    if len(좌표) == 0:
        return None

    # 1) 글씨가 있는 영역만 잘라낸다
    (위, 왼쪽), (아래, 오른쪽) = 좌표.min(axis=0), 좌표.max(axis=0) + 1
    자른_이미지 = 그림.crop((왼쪽, 위, 오른쪽, 아래))

    # 2) 가로세로 비율을 유지한 채 긴 변이 20픽셀이 되도록 줄인다
    너비, 높이 = 자른_이미지.size
    배율 = 숫자_상자_크기 / max(너비, 높이)
    새_너비, 새_높이 = max(1, round(너비 * 배율)), max(1, round(높이 * 배율))
    자른_이미지 = 자른_이미지.resize((새_너비, 새_높이), Image.LANCZOS)

    # 3) 28x28 검은 판 한가운데에 붙인다
    판 = Image.new("L", (모델_입력_크기, 모델_입력_크기), 0)
    판.paste(자른_이미지, ((모델_입력_크기 - 새_너비) // 2, (모델_입력_크기 - 새_높이) // 2))

    # 4) 무게중심이 판의 중심에 오도록 평행 이동한다
    판_배열 = np.array(판, dtype=np.float32)
    세로_격자, 가로_격자 = np.indices(판_배열.shape)
    총합 = 판_배열.sum()
    중심_y = (판_배열 * 세로_격자).sum() / 총합
    중심_x = (판_배열 * 가로_격자).sum() / 총합
    이동_x = (모델_입력_크기 - 1) / 2 - 중심_x
    이동_y = (모델_입력_크기 - 1) / 2 - 중심_y
    return 판.transform(판.size, Image.AFFINE, (1, 0, -이동_x, 0, 1, -이동_y), resample=Image.BILINEAR)


def 텐서로_변환(이미지_28):
    """28x28 'L' 이미지를 정규화된 1x1x28x28 텐서로 바꾼다"""
    배열 = np.array(이미지_28, dtype=np.float32) / 255.0
    텐서 = torch.from_numpy(배열).view(1, 1, 모델_입력_크기, 모델_입력_크기)
    return (텐서 - 정규화_평균) / 정규화_표준편차
